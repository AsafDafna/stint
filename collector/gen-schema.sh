#!/bin/zsh
# Inlines schema.sql into a Swift raw string constant so the binary carries the single source of truth.
# Usage: gen-schema.sh <output.swift>
set -euo pipefail
HERE="${0:A:h}"
OUT="$1"
{
  echo '// GENERATED by collector/gen-schema.sh from collector/schema.sql. Do not edit.'
  echo 'enum Schema {'
  echo '    static let sql = #"""'
  cat "$HERE/schema.sql"
  echo '"""#'
  echo '}'
} > "$OUT"
